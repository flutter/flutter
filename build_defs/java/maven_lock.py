"""Writes maven.lock.bzl: Maven artifacts, pinned by sha256, from a list of coordinates.

The list (android_tests.artifacts beside this file) is a dependency closure
Gradle resolved, one `group:artifact:version` per line; this tool finds each
one's file -- the `.aar` or the `.jar`, at maven.google.com first and Maven
Central second, as test_runner/build.gradle's repositories are ordered -- and
records its URL and sha256. A coordinate with neither file is a BOM (a POM
alone) and is left out with a note. The `maven_artifacts` repository rule
(maven.bzl) fetches the files from the lock.

    python3 maven_lock.py --list android_tests.artifacts --output maven.lock.bzl
"""

import argparse
import hashlib
import sys
import urllib.error
import urllib.request

REPOSITORIES = ["https://maven.google.com", "https://repo1.maven.org/maven2"]
PACKAGINGS = ["aar", "jar"]


def fetch(url):
    try:
        with urllib.request.urlopen(url) as response:
            return response.read()
    except urllib.error.HTTPError as e:
        if e.code == 404:
            return None
        raise


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--list", required=True, help="The coordinates, one per line; # comments.")
    parser.add_argument("--output", required=True, help="The .bzl file to write.")
    args = parser.parse_args(argv)

    coordinates = []
    with open(args.list, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith("#"):
                coordinates.append(line)

    entries = {}
    for coordinate in coordinates:
        group, artifact, version = coordinate.split(":")
        path = "%s/%s/%s/%s-%s" % (group.replace(".", "/"), artifact, version, artifact, version)
        found = None
        for repository in REPOSITORIES:
            for packaging in PACKAGINGS:
                url = "%s/%s.%s" % (repository, path, packaging)
                content = fetch(url)
                if content is not None:
                    found = (packaging, url, hashlib.sha256(content).hexdigest())
                    break
            if found:
                break
        if found is None:
            print(f"note: {coordinate}: no .aar or .jar (a BOM); left out", file=sys.stderr)
            continue
        entries[coordinate] = found
        print(f"{coordinate} {found[0]} {found[2][:12]}", file=sys.stderr)

    with open(args.output, "w", encoding="utf-8") as out:
        out.write("# GENERATED by build_defs/java/maven_lock.py from android_tests.artifacts; do not edit.\n")
        out.write('"""The Maven artifacts of the Android embedding\'s Java tests, pinned.\n\n')
        out.write("Each entry is the artifact's packaging (aar or jar), its file's URL and the\n")
        out.write("file's sha256 (maven.bzl's maven_artifacts fetches them).\n")
        out.write('"""\n\n')
        out.write("MAVEN_ARTIFACTS = {\n")
        for coordinate, (packaging, url, sha256) in sorted(entries.items()):
            out.write(f'    "{coordinate}": {{\n')
            out.write(f'        "packaging": "{packaging}",\n')
            out.write(f'        "sha256": "{sha256}",\n')
            out.write(f'        "url": "{url}",\n')
            out.write("    },\n")
        out.write("}\n")
    print(f"{len(entries)} artifacts -> {args.output}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
