import 'dart:io';

import 'package:gn_to_bazel/gn_to_bazel.dart';
import 'package:path/path.dart' as p;
import 'package:test/test.dart';

void main() {
  const yaml = '''
compile-configs:
  - name: dart2js-canvaskit
    compiler: dart2js
    renderer: canvaskit
  - name: dart2wasm-skwasm
    compiler: dart2wasm
    renderer: skwasm

test-sets:
  - name: engine
    directory: engine
  - name: fallbacks
    directory: fallbacks

test-bundles:
  - name: dart2js-canvaskit-engine
    test-set: engine
    compile-configs: dart2js-canvaskit
  - name: fallbacks
    test-set: fallbacks
    compile-configs:
      - dart2wasm-skwasm
      - dart2js-canvaskit

run-configs:
  - name: chrome
    browser: chrome
    canvaskit-variant: chromium
  - name: safari-wasm
    browser: safari
    wasm-allow-list:
      webkit: true

test-suites:
  - name: chrome-dart2js-canvaskit-engine
    test-bundle: dart2js-canvaskit-engine
    run-config: chrome
    artifact-deps: [ canvaskit_chromium ]
  - name: safari-fallbacks
    test-bundle: fallbacks
    run-config: safari-wasm
    artifact-deps: [ canvaskit, skwasm ]
    enable-ci: false
''';

  group('FeltConfig', () {
    test('reads the five tables and the references among them', () {
      final config = FeltConfig.parse(yaml);
      expect(config.compileConfigs.keys, <String>['dart2js-canvaskit', 'dart2wasm-skwasm']);
      expect(config.compileConfigs['dart2wasm-skwasm']!.compiler, 'dart2wasm');
      expect(config.compileConfigs['dart2wasm-skwasm']!.renderer, 'skwasm');
      expect(config.testSets, <String, String>{'engine': 'engine', 'fallbacks': 'fallbacks'});
      // One compile configuration or a list: a list either way.
      expect(config.testBundles['dart2js-canvaskit-engine']!.compileConfigs, <String>[
        'dart2js-canvaskit',
      ]);
      expect(config.testBundles['fallbacks']!.compileConfigs, <String>[
        'dart2wasm-skwasm',
        'dart2js-canvaskit',
      ]);
      expect(config.testBundles['fallbacks']!.testSet, 'fallbacks');
      // A run configuration is its browser here; the flags and variants are felt's.
      expect(config.runConfigs, <String, String>{'chrome': 'chrome', 'safari-wasm': 'safari'});
      final FeltTestSuite suite = config.testSuites['safari-fallbacks']!;
      expect(suite.testBundle, 'fallbacks');
      expect(suite.runConfig, 'safari-wasm');
      expect(suite.artifactDeps, <String>['canvaskit', 'skwasm']);
      // enable-ci: felt's default is true; a suite that opts out stays off CI.
      expect(suite.enableCi, isFalse);
      expect(config.testSuites['chrome-dart2js-canvaskit-engine']!.enableCi, isTrue);
    });

    test('writes the tables as one Starlark dict, sorted', () {
      final String starlark = FeltConfig.parse(yaml).toStarlark();
      expect(starlark, startsWith('# GENERATED by tools/gn_to_bazel'));
      expect(starlark, contains('FELT_CONFIG = {\n    "compile_configs": {\n'));
      expect(
        starlark,
        contains('"dart2js-canvaskit": {"compiler": "dart2js", "renderer": "canvaskit"},'),
      );
      expect(starlark, contains('    "test_sets": {\n        "engine": "engine",\n'));
      expect(
        starlark,
        contains(
          '        "fallbacks": {\n'
          '            "compile_configs": ["dart2wasm-skwasm", "dart2js-canvaskit"],\n'
          '            "test_set": "fallbacks",\n'
          '        },\n',
        ),
      );
      expect(starlark, contains('        "safari-wasm": {"browser": "safari"},\n'));
      expect(
        starlark,
        contains(
          '        "safari-fallbacks": {\n'
          '            "artifact_deps": ["canvaskit", "skwasm"],\n'
          '            "enable_ci": False,\n'
          '            "run_config": "safari-wasm",\n'
          '            "test_bundle": "fallbacks",\n'
          '        },\n',
        ),
      );
      // Only a suite that opts out carries the key.
      expect(
        starlark,
        contains(
          '        "chrome-dart2js-canvaskit-engine": {\n'
          '            "artifact_deps": ["canvaskit_chromium"],\n'
          '            "run_config": "chrome",\n',
        ),
      );
      // Sorted: chrome's suite before safari's, as buildifier would order the keys.
      expect(
        starlark.indexOf('"chrome-dart2js-canvaskit-engine": {'),
        lessThan(starlark.indexOf('"safari-fallbacks": {')),
      );
    });

    test('rejects a dangling reference, naming the entry', () {
      expect(
        () => FeltConfig.parse(yaml.replaceFirst('run-config: chrome', 'run-config: edge')),
        throwsA(
          isA<FormatException>().having(
            (FormatException e) => e.message,
            'message',
            'test suite chrome-dart2js-canvaskit-engine names an unknown run config: edge',
          ),
        ),
      );
      expect(
        () => FeltConfig.parse(yaml.replaceFirst('test-set: engine', 'test-set: ui')),
        throwsA(
          isA<FormatException>().having(
            (FormatException e) => e.message,
            'message',
            'test bundle dart2js-canvaskit-engine names an unknown test set: ui',
          ),
        ),
      );
      expect(
        () => FeltConfig.parse(
          yaml.replaceFirst('      - dart2wasm-skwasm\n', '      - dart2js-skwasm\n'),
        ),
        throwsA(
          isA<FormatException>().having(
            (FormatException e) => e.message,
            'message',
            'test bundle fallbacks names an unknown compile config: dart2js-skwasm',
          ),
        ),
      );
      expect(
        () => FeltConfig.parse(yaml.replaceFirst('enable-ci: false', 'enable-ci: no')),
        throwsA(
          isA<FormatException>().having(
            (FormatException e) => e.message,
            'message',
            'test suite safari-fallbacks has a non-boolean enable-ci: no',
          ),
        ),
      );
      expect(
        () => FeltConfig.parse(
          '$yaml  - name: safari-fallbacks\n    test-bundle: fallbacks\n    run-config: chrome\n',
        ),
        throwsA(
          isA<FormatException>().having(
            (FormatException e) => e.message,
            'message',
            'duplicate test suite name: safari-fallbacks',
          ),
        ),
      );
    });

    test("reads the engine's own felt_config.yaml", () {
      // test/ of this package is tools/gn_to_bazel/test; the engine is three up.
      final String engine = p.normalize(p.join(Directory.current.path, '..', '..'));
      final file = File(p.join(engine, 'lib', 'web_ui', 'test', 'felt_config.yaml'));
      expect(file.existsSync(), isTrue, reason: file.path);
      final config = FeltConfig.parse(file.readAsStringSync());
      // Every suite's bundle and run configuration resolve (parse would have
      // thrown), and the Linux host's browsers are among the run configurations.
      expect(config.testSuites, isNotEmpty);
      expect(config.runConfigs.values.toSet(), containsAll(<String>['chrome', 'firefox']));
      for (final FeltTestSuite suite in config.testSuites.values) {
        expect(config.testBundles, contains(suite.testBundle));
        expect(config.runConfigs, contains(suite.runConfig));
      }
    });
  });
}
