import 'dart:async';
import 'dart:convert';
import 'dart:io' as io;

import 'package:args/command_runner.dart';
import 'package:path/path.dart' as path;

import 'environment.dart';
import 'felt_config.dart';
import 'package_lock.dart';

class GenerateBuilderJsonCommand extends Command<bool> {
  @override
  String get description =>
      'Generates JSON for the engine_v2 builders to build and copy all artifacts, '
      'compile all test bundles, and run all test suites on all platforms.';

  @override
  String get name => 'generate-builder-json';

  @override
  FutureOr<bool>? run() {
    final packageLock = PackageLock();
    final config = FeltConfig.fromFile(
      path.join(environment.webUiTestDir.path, 'felt_config.yaml'),
    );
    final List<TestSuite> testSuites = config.testSuites.where((suite) => suite.enableCi).toList();
    final Iterable<TestBundle> testBundles = testSuites.map((suite) => suite.testBundle).toSet();
    _writeBuilderJson(
      _generateBuilderJson(
        testBundles.map((TestBundle bundle) => _getBundleBuildStep(bundle)).toList(),
        _getAllTestSteps(testSuites, packageLock),
      ),
      'linux_web_engine_test.json',
    );
    return true;
  }

  void _writeBuilderJson(String builderConfig, String filename) {
    final buildConfigFile = io.File(
      path.join(environment.flutterDirectory.path, 'ci', 'builders', filename),
    );
    buildConfigFile.createSync(recursive: true);
    buildConfigFile.writeAsStringSync('$builderConfig\n');
  }

  String _generateBuilderJson(
    Iterable<Map<String, dynamic>> builds,
    Iterable<Map<String, dynamic>> tests,
  ) {
    final outputJson = <String, dynamic>{
      '_comment': 'THIS IS A GENERATED FILE. Do not edit this file directly.',
      '_comment2': 'See `generate_builder_json.dart` for the generator code',
      'builds': builds,
      'tests': tests,
    };
    return const JsonEncoder.withIndent('  ').convert(outputJson);
  }

  Map<String, dynamic> _getBundleBuildStep(TestBundle bundle) {
    return <String, dynamic>{
      'name': 'web_tests/test_bundles/${bundle.name}',
      'drone_dimensions': <String>['device_type=none', 'os=Linux'],
      'generators': <String, dynamic>{
        'tasks': <dynamic>[
          <String, dynamic>{
            'name': 'compile bundle ${bundle.name}',
            'parameters': <String>['test', '--compile', '--bundle=${bundle.name}'],
            'scripts': <String>['flutter/lib/web_ui/dev/felt'],
          },
        ],
      },
    };
  }

  Map<String, dynamic> _getAnalysisAndLicenseStep() {
    return <String, dynamic>{
      'name': 'web engine analysis and license checks',
      'recipe': 'engine_v2/tester_engine',
      'drone_dimensions': <String>['device_type=none', 'os=Linux'],
      'tasks': <dynamic>[
        <String, dynamic>{
          'name': 'check licenses',
          'parameters': <String>['check-licenses'],
          'script': 'flutter/lib/web_ui/dev/felt',
        },
      ],
    };
  }

  Iterable<Map<String, Object?>> _getAllTestSteps(List<TestSuite> suites, PackageLock packageLock) {
    return <Map<String, Object?>>[
      _getAnalysisAndLicenseStep(),
      ..._getChromeTestSteps(suites, packageLock),
      _getTestStepForPlatformAndBrowser(suites, packageLock, 'Linux', BrowserName.firefox),
      _getTestStepForPlatformAndBrowser(
        suites,
        packageLock,
        'Mac',
        BrowserName.safari,
        specificOS: 'Mac-26.6',
        cpu: 'arm64',
      ),
    ];
  }

  // Shards Chrome suites by renderer, plus one shard for engine, fallbacks
  // and force-st suites.
  Iterable<Map<String, Object?>> _getChromeTestSteps(
    List<TestSuite> suites,
    PackageLock packageLock,
  ) {
    final shards = <String, List<TestSuite>>{};
    for (final TestSuite suite in suites.where(
      (suite) => suite.runConfig.browser == BrowserName.chrome,
    )) {
      shards.putIfAbsent(_chromeShardName(suite), () => <TestSuite>[]).add(suite);
    }
    return <Map<String, Object?>>[
      for (final MapEntry<String, List<TestSuite>> shard in shards.entries)
        _getTestStep(
          name: 'Linux run chrome ${shard.key} suites',
          suites: shard.value,
          packageLock: packageLock,
          browser: BrowserName.chrome,
          droneDimensions: <String>['device_type=none', 'os=Linux'],
        ),
    ];
  }

  String _chromeShardName(TestSuite suite) {
    final String testSet = suite.testBundle.testSet.name;
    if (testSet == 'engine' ||
        testSet == 'fallbacks' ||
        suite.runConfig.forceSingleThreadedSkwasm) {
      return 'engine, fallbacks and force-st';
    }
    return suite.testBundle.compileConfigs.first.renderer.name;
  }

  Map<String, Object?> _getTestStepForPlatformAndBrowser(
    List<TestSuite> suites,
    PackageLock packageLock,
    String platform,
    BrowserName browser, {
    String? specificOS,
    String? cpu,
  }) {
    return _getTestStep(
      name: '$platform run ${browser.name} suites',
      suites: suites.where((suite) => suite.runConfig.browser == browser),
      packageLock: packageLock,
      browser: browser,
      droneDimensions: <String>[
        'device_type=none',
        'os=${specificOS ?? platform}',
        if (cpu != null) 'cpu=$cpu',
      ],
    );
  }

  Map<String, Object?> _getTestStep({
    required String name,
    required Iterable<TestSuite> suites,
    required PackageLock packageLock,
    required BrowserName browser,
    required List<String> droneDimensions,
  }) {
    final Set<TestBundle> bundles = suites.map((suite) => suite.testBundle).toSet();
    return <String, Object?>{
      'name': name,
      'recipe': 'engine_v2/tester_engine',
      'drone_dimensions': droneDimensions,
      'gclient_variables': <String, Object?>{'download_android_deps': false},
      'dependencies': <String>[...bundles.map((bundle) => 'web_tests/test_bundles/${bundle.name}')],
      'test_dependencies': <Object?>[
        <String, Object?>{
          'dependency': 'goldctl',
          'version': 'git_revision:720a542f6fe4f92922c3b8f0fdcc4d2ac6bb83cd',
        },
        if (browser == BrowserName.chrome)
          <String, Object?>{
            'dependency': 'chrome_and_driver',
            'version': packageLock.chromeLock.version,
          },
        if (browser == BrowserName.firefox)
          <String, Object?>{
            'dependency': 'firefox',
            'version': 'version:${packageLock.firefoxLock.version}',
          },
      ],
      'tasks': <Object?>[
        <String, Object?>{
          'name': 'copy artifacts',
          'parameters': <String>[
            'test',
            '--copy-artifacts',
            for (final TestSuite suite in suites) '--suite=${suite.name}',
          ],
          'script': 'flutter/lib/web_ui/dev/felt',
        },
        ...suites.map(
          (suite) => <String, Object?>{
            'name': 'run suite ${suite.name}',
            'parameters': <String>['test', '--run', '--suite=${suite.name}'],
            'script': 'flutter/lib/web_ui/dev/felt',
          },
        ),
      ],
    };
  }
}
