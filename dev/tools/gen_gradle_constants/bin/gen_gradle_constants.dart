// ## Usage
//
// Run this program from the root of the git repository.
//
// ```
// dart dev/tools/gen_gradle_constants/bin/gen_gradle_constants.dart
// ```

import 'dart:io';
import 'package:path/path.dart' as path;

Future<void> main(List<String> args) async {
  final String rootDir = path.dirname(
    path.dirname(path.dirname(path.dirname(path.dirname(path.fromUri(Platform.script))))),
  );
  final String inputFile = path.join(
    rootDir,
    'packages',
    'flutter_tools',
    'lib',
    'src',
    'android',
    'gradle_constants.dart',
  );
  final String kotlinOut = path.join(
    rootDir,
    'packages',
    'flutter_tools',
    'gradle',
    'src',
    'main',
    'kotlin',
    'GradleConstants.g.kt',
  );
  final String copyrightHeader = path.join(
    rootDir,
    'dev',
    'tools',
    'gen_gradle_constants',
    'copyright.txt',
  );
  final ProcessResult result = await Process.run(path.join(rootDir, 'bin', 'dart'), <String>[
    'run',
    'pigeon',
    '--input',
    inputFile,
    '--kotlin_out',
    kotlinOut,
    '--kotlin_package',
    'com.flutter.gradle',
    '--copyright_header',
    copyrightHeader,
    '--one_language',
  ], workingDirectory: rootDir);
  stdout.write(result.stdout);
  stderr.write(result.stderr);
  if (result.exitCode != 0) {
    exit(result.exitCode);
  }
  // Clean up unused Android/Flutter runtime imports and empty codec boilerplate
  // unconditionally generated by Pigeon, since FGP is a Gradle JVM plugin.
  final generatedKotlin = File(kotlinOut);
  final List<String> lines = generatedKotlin.readAsLinesSync();
  final cleaned = StringBuffer();
  for (final line in lines) {
    if (line.startsWith('import android.util.Log') ||
        line.startsWith('import io.flutter.plugin.common.') ||
        line.startsWith('import java.io.ByteArrayOutputStream') ||
        line.startsWith('import java.nio.ByteBuffer')) {
      continue;
    }
    if (line.startsWith('private open class') ||
        line.startsWith('private object') ||
        line.startsWith('class FlutterError') ||
        line.startsWith('/**')) {
      break;
    }
    cleaned.writeln(line);
  }
  generatedKotlin.writeAsStringSync('${cleaned.toString().trimRight()}\n');

  print('Successfully generated Gradle build constants.');
}
