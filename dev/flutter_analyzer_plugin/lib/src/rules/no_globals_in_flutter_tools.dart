import 'package:analyzer/analysis_rule/analysis_rule.dart';
import 'package:analyzer/analysis_rule/rule_context.dart';
import 'package:analyzer/analysis_rule/rule_visitor_registry.dart';
import 'package:analyzer/dart/ast/ast.dart';
import 'package:analyzer/dart/ast/visitor.dart';
import 'package:analyzer/error/error.dart';

import 'no_globals_in_flutter_tools_restricted_paths.dart' as paths;

const String _flutterToolsPackageName = 'flutter_tools';
const String _flutterToolsPackagePath = 'packages/flutter_tools/';
const String _globalsFileName = 'globals.dart';
const String _packageScheme = 'package';

/// Verifies that `globals.dart` is not imported in migrated `flutter_tools` files.
///
/// As part of the modular dependency injection refactoring in `flutter_tools`,
/// commands, runners, and services are being migrated to receive dependencies
/// explicitly via constructor injection rather than accessing ambient singleton
/// services exported by `packages/flutter_tools/lib/src/globals.dart`.
///
/// This rule acts as a migration ratchet: any file listed in [restrictedPaths]
/// (by default [defaultRestrictedPaths]) that imports `globals.dart` either
/// through relative imports (e.g. `import '../globals.dart';`) or package imports
/// (e.g. `import 'package:flutter_tools/src/globals.dart';`) will produce a
/// compile-time analysis error.
///
/// To update [defaultRestrictedPaths] automatically whenever additional files are
/// migrated, run:
/// ```bash
/// dart dev/flutter_analyzer_plugin/tool/update_migrated_files.dart
/// ```
/// or from `packages/flutter_tools/`:
/// ```bash
/// dart tool/update_migrated_globals.dart
/// ```
class NoGlobalsInFlutterTools extends AnalysisRule {
  /// Creates a new instance of [NoGlobalsInFlutterTools].
  ///
  /// If [restrictedPaths] is provided, it overrides [defaultRestrictedPaths].
  /// Any Windows path separators (`\`) in [restrictedPaths] are automatically
  /// normalized to POSIX separators (`/`).
  NoGlobalsInFlutterTools([Set<String>? restrictedPaths])
    : restrictedPaths =
          restrictedPaths?.map((String p) => p.replaceAll(r'\', '/')).toSet() ??
          defaultRestrictedPaths,
      super(
        name: code.name,
        description: 'Verify that globals.dart is not imported in migrated flutter_tools files.',
      );

  /// Diagnostic error emitted when a restricted file imports `globals.dart`.
  static const LintCode code = LintCode(
    'no_globals_in_flutter_tools',
    'Do not import globals.dart in this file.',
    correctionMessage:
        'Pass dependencies explicitly via constructor parameters rather than accessing ambient globals.',
    severity: DiagnosticSeverity.ERROR,
  );

  /// Default set of file paths relative to `packages/flutter_tools/` that must
  /// not import `globals.dart`.
  ///
  /// This list is auto-generated by `dev/flutter_analyzer_plugin/tool/update_migrated_files.dart`.
  static const Set<String> defaultRestrictedPaths = paths.defaultRestrictedPaths;

  /// The active set of restricted file paths relative to `packages/flutter_tools/`.
  final Set<String> restrictedPaths;

  @override
  LintCode get diagnosticCode => code;

  @override
  void registerNodeProcessors(RuleVisitorRegistry registry, RuleContext context) {
    // Normalize path separators to POSIX slashes for cross-platform matching.
    final String filePath = context.definingUnit.file.path.replaceAll(r'\', '/');

    // Find the last occurrence of 'packages/flutter_tools/' to guard against parent
    // directories that happen to contain the same substring.
    final int toolIndex = filePath.lastIndexOf(_flutterToolsPackagePath);
    if (toolIndex == -1 || (toolIndex > 0 && filePath[toolIndex - 1] != '/')) {
      return;
    }

    // Extract the relative path within packages/flutter_tools/ (e.g. 'lib/src/commands/clean.dart').
    final String relativePath = filePath.substring(toolIndex + _flutterToolsPackagePath.length);

    // Only register AST visitors if the file is included in the restricted set.
    if (!restrictedPaths.contains(relativePath)) {
      return;
    }

    final visitor = _Visitor(this);
    registry.addImportDirective(this, visitor);
  }
}

/// AST visitor that inspects import directives for `globals.dart` imports.
class _Visitor extends SimpleAstVisitor<void> {
  _Visitor(this.rule);

  final AnalysisRule rule;

  @override
  void visitImportDirective(ImportDirective node) {
    if (node.uri.stringValue case final String uriStr) {
      final Uri? uri = Uri.tryParse(uriStr);
      if (uri == null || uri.pathSegments.isEmpty) {
        return;
      }

      // Check whether the imported target file is globals.dart.
      if (uri.pathSegments.last != _globalsFileName) {
        return;
      }

      // Flag relative imports (no scheme) or package:flutter_tools imports.
      // Third-party packages (e.g. package:other_pkg/globals.dart) are ignored.
      if (!uri.hasScheme ||
          (uri.isScheme(_packageScheme) && uri.pathSegments.first == _flutterToolsPackageName)) {
        rule.reportAtNode(node.uri);
      }
    }
  }
}
